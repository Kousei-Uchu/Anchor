// Copies the Remotion promo into the website so <Player> can play it live.
//
//   npm run sync:promo
//
// Source of truth stays in ../remotion-project. This copies:
//   src/Promo.tsx, src/music.json  ->  website/src/promo/
//   public/shots/*.jpg             ->  website/public/shots/
//   public/ambient.wav             ->  website/public/ambient.mp3  (~1 MB instead of 11 MB; needs ffmpeg)
//
// The copies are committed, so the website builds on its own (for example on Vercel with
// Root Directory set to `website`). Re-run this after you change the video.
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '..');
const src = resolve(site, '../remotion-project');

if (!existsSync(src)) {
  console.error(`remotion-project not found at ${src}`);
  process.exit(1);
}

mkdirSync(join(site, 'src/promo'), { recursive: true });
mkdirSync(join(site, 'public/shots'), { recursive: true });

const banner =
  '// GENERATED by `npm run sync:promo` from remotion-project/src/Promo.tsx. Edit the original, not this copy.\n';
const promo = readFileSync(join(src, 'src/Promo.tsx'), 'utf8').replace(/ambient\.wav/g, 'ambient.mp3');
writeFileSync(join(site, 'src/promo/Promo.tsx'), banner + promo);
cpSync(join(src, 'src/music.json'), join(site, 'src/promo/music.json'));

for (const f of readdirSync(join(src, 'public/shots'))) {
  cpSync(join(src, 'public/shots', f), join(site, 'public/shots', f));
}

const wav = join(src, 'public/ambient.wav');
if (existsSync(wav)) {
  try {
    execFileSync(
      'ffmpeg',
      ['-y', '-loglevel', 'error', '-i', wav, '-c:a', 'libmp3lame', '-q:a', '3', join(site, 'public/ambient.mp3')],
      { stdio: 'inherit' },
    );
    console.log('audio: ambient.wav -> public/ambient.mp3');
  } catch {
    console.warn('ffmpeg not available: kept the existing public/ambient.mp3 (install ffmpeg to refresh the audio)');
  }
}
console.log('promo synced');
